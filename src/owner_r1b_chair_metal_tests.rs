//! Finite real-chair floor contact and absent-Follow roundtrip on actual Metal.
use super::*;
#[test]
#[ignore = "explicit serialized Metal; fresh HAIR_OWNER_R1B_CHAIR_OUTPUT/FIXTURES required"]
fn owner_r1b_actual_metal_chair_floor_and_graybox_return_same_pose() {
    let output = PathBuf::from(std::env::var_os("HAIR_OWNER_R1B_CHAIR_OUTPUT").expect("exclusive output"));
    let fixtures = PathBuf::from(std::env::var_os("HAIR_OWNER_R1B_CHAIR_FIXTURES").expect("owned fixtures"));
    let mut a = app();
    assert_eq!(output.parent(), a.root.parent());
    assert_eq!(fixtures.parent().unwrap().canonicalize().unwrap(), std::env::temp_dir().canonicalize().unwrap());
    std::fs::create_dir(&output).unwrap(); std::fs::create_dir(&fixtures).unwrap();
    let data = fixtures.join("folder"); std::fs::create_dir(&data).unwrap();
    for name in ["A.txt", "Z.txt"] { std::fs::write(data.join(name), name.as_bytes()).unwrap(); }
    a.themes.push(hair::theme::Theme::load(&a.root.join("packs/archive.toml"), &mut Default::default()).unwrap());
    a.complete_folder(Ok(Some(data.clone()))).unwrap();
    let backend = attach(&mut a);
    tap(&mut a, KeyCode::KeyP); tap(&mut a, KeyCode::KeyB); tap(&mut a, KeyCode::Enter);
    tap(&mut a, KeyCode::Escape); tap(&mut a, KeyCode::KeyN);
    aim_floor(&mut a, [-2., 0.]);
    let d = a.decoration_position().unwrap();
    assert_eq!(d.tag, "hair.seating.chair");
    let floor = a.themes[0].host.vertices()[..36].iter().map(|v| v.position[1]).fold(f32::NEG_INFINITY, f32::max);
    let mesh = a.place_preview().unwrap();
    let lo = mesh.iter().map(|v| v.position[1]).fold(f32::INFINITY, f32::min);
    assert!((lo - floor).abs() < 0.000001);
    assert!(mesh.iter().all(|v| v.position[1] <= d.size[1] + 0.000001));
    assert_eq!(d.bounds().unwrap().at[1], 0.);
    let scene = a.place_scene_at(0.);
    let preview = shot(&mut a, &output, "chair-preview-real-floor", &backend, &scene);
    preview_controls(&mut a, &output, "r1b-chair", &backend, &scene, &preview, PENDING);
    tap(&mut a, KeyCode::Enter);
    shot(&mut a, &output, "chair-frozen-real-floor", &backend, &scene);
    tap(&mut a, KeyCode::Enter);
    assert!(a.local_status.contains("decoration saved"), "{}", a.local_status);
    tap(&mut a, KeyCode::KeyP);
    let saved = layout(&a); let host = a.themes[0].host.clone(); let pinned = records(&data);
    a.pose = Pose { position: [d.at[0], d.at[1] + 1.65], pitch: ((d.size[1] * 0.5 - 1.65) / 1.65).atan(), ..Default::default() };
    let pose = a.pose;
    let scene = a.place_scene_at(0.);
    let positive = shot(&mut a, &output, "chair-saved-real-floor", &backend, &scene);
    let actual = a.themes[0].decoration_preview(&d).unwrap();
    let buried: Vec<_> = actual.iter().map(|v| Vertex { position: [v.position[0], v.position[1] - floor, v.position[2]], ..*v }).collect();
    assert!(buried.iter().any(|v| v.position[1] < floor - 0.000001));
    let altered = substitute(&scene, &actual, &buried);
    a.renderer.as_mut().unwrap().set_scene(&altered);
    let negative = shot(&mut a, &output, "chair-buried-005-negative", &backend, &altered);
    let changed = changed_world_pixels(&positive, &negative);
    assert!(changed > 100, "floor contact counterfactual must change actual world pixels: {changed}");
    a.place_scene_refresh();
    tap(&mut a, KeyCode::F5);
    invariant(&a, &saved, &host, &data, &pinned);
    a.pose = pose;
    let refreshed = shot(&mut a, &output, "chair-refreshed-real-floor", &backend, &scene);
    assert_eq!(changed_world_pixels(&positive, &refreshed), 0);
    switch_by_input(&mut a); assert_eq!(a.theme_index, 1);
    assert_eq!(a.pose.position, pose.position); assert_eq!(a.pose.pitch, pose.pitch);
    invariant(&a, &saved, &host, &data, &pinned);
    let gray = a.themes[1].decoration_preview(&d).unwrap();
    assert!(gray[..36].iter().all(|v| v.color == [0.5; 3] && v.texture == 0));
    let gray_scene = a.place_scene_at(0.);
    let gray_pixels = shot(&mut a, &output, "missing-graybox-same-pose", &backend, &gray_scene);
    let erased = substitute(&gray_scene, &gray, &[]);
    a.renderer.as_mut().unwrap().set_scene(&erased);
    let erased_pixels = shot(&mut a, &output, "graybox-erased-negative", &backend, &erased);
    assert!(changed_world_pixels(&gray_pixels, &erased_pixels) > 100);
    a.place_scene_refresh();
    switch_by_input(&mut a); assert_eq!(a.theme_index, 0);
    invariant(&a, &saved, &host, &data, &pinned);
    let returned = shot(&mut a, &output, "authentic-chair-return-same-pose", &backend, &scene);
    assert_eq!(changed_world_pixels(&positive, &returned), 0);
    a.renderer.take().unwrap().wait().unwrap(); drop(a);
    let mut cold = app(); cold.complete_folder(Ok(Some(data.clone()))).unwrap();
    invariant(&cold, &saved, &host, &data, &pinned); cold.pose = pose;
    let backend = attach(&mut cold);
    let cold_pixels = shot(&mut cold, &output, "cold-authentic-chair-real-floor", &backend, &scene);
    assert_eq!(changed_world_pixels(&positive, &cold_pixels), 0);
    cold.renderer.take().unwrap().wait().unwrap();
    std::fs::write(output.join("WITNESS-PASS.txt"), format!("Actual offscreen Metal chair preview/frozen/saved/refresh/cold and graybox->authentic roundtrip at same saved and camera pose. Actual slab top={floor}, chair minY={lo}, logical bottom=0, logical top={}; buried-0.05 negative changed world pixels={changed}; graybox-erasure negative passed. App synthetic inputs; no physical/native/human acceptance. Records bytes/inodes unchanged on view/refresh/switch/open. package_ready=false.\n", d.size[1])).unwrap();
}
